const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const envExamplePath = path.join(rootDir, '.env.example');

// Default fallback values
let googleMapsApiKey = '';
let apiBaseUrl = 'https://histeria-buymass-dev.work.gd';

// Create .env from template if missing
if (!fs.existsSync(envPath)) {
  const defaultEnvContent = `# BuyMass Store Admin — Local Environment Variables
# Add your Google Maps JavaScript API key below to enable live maps & places autocomplete
GOOGLE_MAPS_API_KEY=

# Backend REST API endpoint
API_BASE_URL=https://histeria-buymass-dev.work.gd
`;
  fs.writeFileSync(envPath, defaultEnvContent, 'utf8');
  console.log('[set-env] Created default .env file in project root');
}

// Always ensure .env.example exists
if (!fs.existsSync(envExamplePath)) {
  const exampleContent = `# BuyMass Store Admin — Environment Template
GOOGLE_MAPS_API_KEY=your_google_maps_api_key_here
API_BASE_URL=https://histeria-buymass-dev.work.gd
`;
  fs.writeFileSync(envExamplePath, exampleContent, 'utf8');
}

// Parse .env
if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf8');
  content.split('\n').forEach((line) => {
    const trimmed = line.trim();
    if (trimmed && !trimmed.startsWith('#')) {
      const eqIndex = trimmed.indexOf('=');
      if (eqIndex > -1) {
        const key = trimmed.slice(0, eqIndex).trim();
        const rawVal = trimmed.slice(eqIndex + 1).trim();
        const val = rawVal.replace(/^["']|["']$/g, '');

        if (key === 'GOOGLE_MAPS_API_KEY' || key === 'NG_APP_GOOGLE_MAPS_API_KEY') {
          googleMapsApiKey = val;
        }
        if (key === 'API_BASE_URL' || key === 'BACKEND_URL') {
          apiBaseUrl = val;
        }
      }
    }
  });
}

// Write src/environments/environment.ts
const envTsContent = `// Auto-generated by scripts/set-env.js. Do not edit manually; update .env instead.
export const environment = {
  production: false,
  apiBaseUrl: '${apiBaseUrl}',
  googleMapsApiKey: '${googleMapsApiKey}',
  appName: 'BuyMass Store Admin',
  enableMockAnalytics: true,
};
`;

// Write src/environments/environment.prod.ts
const envProdTsContent = `// Auto-generated by scripts/set-env.js. Do not edit manually; update .env instead.
export const environment = {
  production: true,
  apiBaseUrl: '${apiBaseUrl}',
  googleMapsApiKey: '${googleMapsApiKey}',
  appName: 'BuyMass Store Admin',
  enableMockAnalytics: false,
};
`;

const envDir = path.join(rootDir, 'src', 'environments');
if (!fs.existsSync(envDir)) {
  fs.mkdirSync(envDir, { recursive: true });
}

fs.writeFileSync(path.join(envDir, 'environment.ts'), envTsContent, 'utf8');
fs.writeFileSync(path.join(envDir, 'environment.prod.ts'), envProdTsContent, 'utf8');

console.log(`[set-env] Synchronized environment configs from .env (Google Maps Key: ${googleMapsApiKey ? 'Configured' : 'Not set'})`);
