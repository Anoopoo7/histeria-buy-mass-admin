const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const envExamplePath = path.join(rootDir, '.env.example');

// 1. Initialize with process.env (Vercel / CI takes precedence)
let googleMapsApiKey = process.env.GOOGLE_MAPS_API_KEY || '';
let apiBaseUrl = process.env.API_BASE_URL || 'https://histeria-buymass-dev.work.gd';
let cloudinaryCloudName = process.env.CLOUDINARY_CLOUD_NAME || '';
let cloudinaryUploadPreset = process.env.CLOUDINARY_UPLOAD_PRESET || '';
let cloudinaryApiKey = process.env.CLOUDINARY_API_KEY || '';

let newRelicAccountId = process.env.NEW_RELIC_ACCOUNT_ID || '';
let newRelicApplicationId = process.env.NEW_RELIC_APPLICATION_ID || '';
let newRelicLicenseKey = process.env.NEW_RELIC_LICENSE_KEY || '';
let newRelicTrustKey = process.env.NEW_RELIC_TRUST_KEY || '';

// 2. Parse local .env file if present (fallbacks when process.env is empty)
if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf8');
  content.split('\n').forEach((line) => {
    const trimmed = line.trim();
    if (trimmed && !trimmed.startsWith('#')) {
      const eqIndex = trimmed.indexOf('=');
      if (eqIndex > -1) {
        const key = trimmed.slice(0, eqIndex).trim();
        const rawVal = trimmed.slice(eqIndex + 1).trim();
        const val = rawVal.replace(/^["']|["']$/g, '');

        if (!googleMapsApiKey && (key === 'GOOGLE_MAPS_API_KEY' || key === 'NG_APP_GOOGLE_MAPS_API_KEY')) {
          googleMapsApiKey = val;
        }
        if (key === 'API_BASE_URL' || key === 'BACKEND_URL') {
          if (!process.env.API_BASE_URL && !process.env.BACKEND_URL) apiBaseUrl = val;
        }
        if (!cloudinaryCloudName && key === 'CLOUDINARY_CLOUD_NAME') {
          cloudinaryCloudName = val;
        }
        if (!cloudinaryUploadPreset && key === 'CLOUDINARY_UPLOAD_PRESET') {
          cloudinaryUploadPreset = val;
        }
        if (!cloudinaryApiKey && key === 'CLOUDINARY_API_KEY') {
          cloudinaryApiKey = val;
        }
        if (!newRelicAccountId && key === 'NEW_RELIC_ACCOUNT_ID') {
          newRelicAccountId = val;
        }
        if (!newRelicApplicationId && key === 'NEW_RELIC_APPLICATION_ID') {
          newRelicApplicationId = val;
        }
        if (!newRelicLicenseKey && key === 'NEW_RELIC_LICENSE_KEY') {
          newRelicLicenseKey = val;
        }
        if (!newRelicTrustKey && key === 'NEW_RELIC_TRUST_KEY') {
          newRelicTrustKey = val;
        }
      }
    }
  });
}

// 3. Update .env.example template
const exampleContent = `# BuyMass Store Admin — Environment Template
GOOGLE_MAPS_API_KEY=your_google_maps_api_key_here
API_BASE_URL=https://histeria-buymass-dev.work.gd

# Cloudinary Credentials (Direct browser uploads for store photographs & KYC documents)
CLOUDINARY_CLOUD_NAME=your_cloud_name_here
CLOUDINARY_UPLOAD_PRESET=your_unsigned_upload_preset
CLOUDINARY_API_KEY=your_api_key_here

# New Relic Browser Telemetry (Frontend Metrics, Core Web Vitals, Error Tracking)
# Obtain from New Relic One: Add Data -> Browser Monitoring -> Copy/Paste Snippet or Application Settings
NEW_RELIC_ACCOUNT_ID=
NEW_RELIC_APPLICATION_ID=
NEW_RELIC_LICENSE_KEY=
NEW_RELIC_TRUST_KEY=
`;
fs.writeFileSync(envExamplePath, exampleContent, 'utf8');

const isNewRelicConfigured = Boolean(newRelicLicenseKey && newRelicApplicationId);

// 4. Write src/environments/environment.ts
const envTsContent = `// Auto-generated by scripts/set-env.js. Do not edit manually; update .env or Vercel Environment Variables instead.
export const environment = {
  production: false,
  apiBaseUrl: '${apiBaseUrl}',
  googleMapsApiKey: '${googleMapsApiKey}',
  cloudinary: {
    cloudName: '${cloudinaryCloudName}',
    uploadPreset: '${cloudinaryUploadPreset}',
    apiKey: '${cloudinaryApiKey}',
  },
  newRelic: {
    accountId: '${newRelicAccountId}',
    applicationId: '${newRelicApplicationId}',
    licenseKey: '${newRelicLicenseKey}',
    trustKey: '${newRelicTrustKey || newRelicAccountId}',
    enabled: ${isNewRelicConfigured},
  },
  appName: 'BuyMass Store Admin',
  enableMockAnalytics: true,
};
`;

// 5. Write src/environments/environment.prod.ts
const envProdTsContent = `// Auto-generated by scripts/set-env.js. Do not edit manually; update .env or Vercel Environment Variables instead.
export const environment = {
  production: true,
  apiBaseUrl: '${apiBaseUrl}',
  googleMapsApiKey: '${googleMapsApiKey}',
  cloudinary: {
    cloudName: '${cloudinaryCloudName}',
    uploadPreset: '${cloudinaryUploadPreset}',
    apiKey: '${cloudinaryApiKey}',
  },
  newRelic: {
    accountId: '${newRelicAccountId}',
    applicationId: '${newRelicApplicationId}',
    licenseKey: '${newRelicLicenseKey}',
    trustKey: '${newRelicTrustKey || newRelicAccountId}',
    enabled: ${isNewRelicConfigured},
  },
  appName: 'BuyMass Store Admin',
  enableMockAnalytics: false,
};
`;

const envDir = path.join(rootDir, 'src', 'environments');
if (!fs.existsSync(envDir)) {
  fs.mkdirSync(envDir, { recursive: true });
}
fs.writeFileSync(path.join(envDir, 'environment.ts'), envTsContent, 'utf8');
fs.writeFileSync(path.join(envDir, 'environment.prod.ts'), envProdTsContent, 'utf8');

// 6. Inject or reset New Relic Browser Agent snippet in src/index.html
const indexPath = path.join(rootDir, 'src', 'index.html');
if (fs.existsSync(indexPath)) {
  let indexHtml = fs.readFileSync(indexPath, 'utf8');
  const placeholderRegex = /(<!-- NEW_RELIC_BROWSER_AGENT_START -->[\s\S]*?<!-- NEW_RELIC_BROWSER_AGENT_END -->|<!-- NEW_RELIC_BROWSER_AGENT -->)/;

  if (isNewRelicConfigured) {
    const nrSnippet = `<!-- NEW_RELIC_BROWSER_AGENT_START -->
  <!-- New Relic Browser SPA Monitoring (Injected automatically by set-env.js) -->
  <script type="text/javascript">
    window.NREUM||(NREUM={});NREUM.info={beacon:"bam.nr-data.net",errorBeacon:"bam.nr-data.net",licenseKey:"${newRelicLicenseKey}",applicationID:"${newRelicApplicationId}",sa:1};NREUM.loader_config={accountID:"${newRelicAccountId}",trustKey:"${newRelicTrustKey || newRelicAccountId}",agentID:"${newRelicApplicationId}",licenseKey:"${newRelicLicenseKey}",applicationID:"${newRelicApplicationId}"};
  </script>
  <script type="text/javascript" src="https://js-agent.newrelic.com/nr-spa.min.js"></script>
  <!-- NEW_RELIC_BROWSER_AGENT_END -->`;

    indexHtml = indexHtml.replace(placeholderRegex, nrSnippet);
  } else {
    indexHtml = indexHtml.replace(placeholderRegex, '<!-- NEW_RELIC_BROWSER_AGENT -->');
  }

  fs.writeFileSync(indexPath, indexHtml, 'utf8');
}

console.log(
  `[set-env] Synchronized environment configs (Cloudinary: ${cloudinaryCloudName ? 'Configured' : 'Not set'}, New Relic: ${isNewRelicConfigured ? 'Configured' : 'Disabled'})`
);
